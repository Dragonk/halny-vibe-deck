#[cfg(test)]
mod terms_tests {
    use super::*;

    #[test]
    fn terms_translate_modes_and_thinking() {
        assert_eq!(option_term("pl", "mode", "accept-edits"), Some("Akceptuj edycje"));
        assert_eq!(option_term("de", "thinking", "high"), Some("Hoch"));
        assert_eq!(option_term("it", "thinking", "off"), Some("Disattivato"));
        // Unknown language falls back to English.
        assert_eq!(option_term("xx", "mode", "ask"), Some("Ask"));
        // Unknown values and option ids pass through untouched.
        assert_eq!(option_term("en", "mode", "nonexistent"), None);
        assert_eq!(option_term("en", "model", "mistral"), None);
        assert_eq!(
            option_term_desc("pl", "mode", "smart-approve"),
            Some("Agent sam decyduje, co może bezpiecznie zatwierdzić")
        );
        assert_eq!(
            option_term_desc("en", "thinking", "max"),
            Some("Maximum reasoning: slowest and most thorough")
        );
    }

    #[test]
    fn new_keys_available_in_all_languages() {
        let sample = [
            "serveTab",
            "updatesSectionTitle",
            "closeSessionLabel",
            "newSessionChooseFolder",
            "agentDisplayName",
        ];
        for key in sample {
            for lang in ["en", "pl", "fr", "es", "de", "it"] {
                assert!(!tr(lang, key).is_empty(), "missing {key} for {lang}");
            }
        }
        assert_eq!(tr("pl", "remoteTab"), "Zdalne SSH");
        assert_eq!(tr("pl", "servePort"), "Port");
    }
}
