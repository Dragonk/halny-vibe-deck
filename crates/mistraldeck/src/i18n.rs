fn terms_entry(
    table: &'static [(&'static str, &'static [(&'static str, &'static str, &'static str)])],
    lang: &str,
    value: &str,
) -> Option<(&'static str, &'static str)> {
    let entries = table
        .iter()
        .find(|(code, _)| *code == lang)
        .map(|(_, e)| *e)
        .or_else(|| table.iter().find(|(code, _)| *code == "en").map(|(_, e)| *e))?;
    entries
        .iter()
        .find(|(v, _, _)| *v == value)
        .map(|(_, n, d)| (*n, *d))
}

/// Localized display name of a mode/thinking config option value
/// ("accept-edits", "medium", ...). Unknown values -> None (caller
/// keeps the raw name, e.g. custom agent modes).
pub fn option_term(lang: &str, option_id: &str, value: &str) -> Option<&'static str> {
    match option_id {
        "mode" => terms_entry(MODE_TERMS, lang, value).map(|e| e.0),
        "thinking" => terms_entry(THINKING_TERMS, lang, value).map(|e| e.0),
        _ => None,
    }
}

/// Localized description of a mode/thinking config option value
/// (dropdown item subtitle).
pub fn option_term_desc(lang: &str, option_id: &str, value: &str) -> Option<&'static str> {
    match option_id {
        "mode" => terms_entry(MODE_TERMS, lang, value).map(|e| e.1),
        "thinking" => terms_entry(THINKING_TERMS, lang, value).map(|e| e.1),
        _ => None,
    }
}

/// Resolve a translation for the given language code ("en", "pl", ...).
/// Falls back to English, then to the key itself.
pub fn tr(lang: &str, key: &str) -> &'static str {
    for (code, table) in TRANSLATIONS {
        if *code == lang {
            for (k, v) in table.iter() {
                if *k == key {
                    return v;
                }
            }
        }
    }
    for (k, v) in TRANSLATIONS[0].1.iter() {
        if *k == key {
            return v;
        }
    }
    ""
}

/// Translation with {{var}} placeholder substitution.
pub fn tf(lang: &str, key: &str, vars: &[(&str, &str)]) -> String {
    let mut s = tr(lang, key).to_string();
    for (name, val) in vars {
        s = s.replace(&format!("{{{{{}}}}}", name), val);
    }
    s
}

