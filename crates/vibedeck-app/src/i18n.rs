//! Minimal i18n: English and Polish, chosen at runtime.
//! Adding a language = adding one more `Str` struct (same keys).

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Lang {
    En,
    Pl,
}

impl Lang {
    pub fn from_code(code: &str) -> Self {
        match code {
            "pl" => Lang::Pl,
            _ => Lang::En,
        }
    }

    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Pl => "pl",
        }
    }
}

