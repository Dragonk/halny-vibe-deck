//! Minimal i18n: English, Polish, German, French, Spanish, Italian —
//! chosen at runtime ("Automatic (System)" follows the OS locale).
//! Adding a language = adding one more `Str` struct (same keys).

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Lang {
    En,
    Pl,
    De,
    Fr,
    Es,
    It,
}

impl Lang {
    /// All supported UI languages, in combo-box order.
    pub const ALL: [Lang; 6] = [Lang::En, Lang::Pl, Lang::De, Lang::Fr, Lang::Es, Lang::It];

    /// Legacy helper — kept for config files that store a plain code.
    #[allow(dead_code)]
    pub fn from_code(code: &str) -> Self {
        match code {
            "pl" => Lang::Pl,
            "de" => Lang::De,
            "fr" => Lang::Fr,
            "es" => Lang::Es,
            "it" => Lang::It,
            _ => Lang::En,
        }
    }

    /// Resolve a preference ("system" | "en" | "pl" | …) into a UI language.
    /// "system" sniffs the OS locale; unknown locales fall back to English.
    pub fn resolve(code: &str) -> Self {
        match code {
            "en" => Lang::En,
            "pl" => Lang::Pl,
            "de" => Lang::De,
            "fr" => Lang::Fr,
            "es" => Lang::Es,
            "it" => Lang::It,
            _ => {
                let locale = sys_locale::get_locale()
                    .unwrap_or_default()
                    .to_lowercase();
                for lang in Lang::ALL {
                    if locale.starts_with(lang.code()) {
                        return lang;
                    }
                }
                Lang::En
            }
        }
    }

    #[allow(dead_code)]
    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Pl => "pl",
            Lang::De => "de",
            Lang::Fr => "fr",
            Lang::Es => "es",
            Lang::It => "it",
        }
    }

    /// The language's own name, shown in the settings combo box.
    pub fn native_name(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::Pl => "Polski",
            Lang::De => "Deutsch",
            Lang::Fr => "Français",
            Lang::Es => "Español",
            Lang::It => "Italiano",
        }
    }
}

